/**
 * Cookies brought in by 从浏览器导入 (SEC-10, MAIN-4).
 *
 * Emperor never uses the Keychain, so Chromium runs with a mock one and its
 * own cookie encryption has only a fixed password: whatever a profile's
 * `Cookies` database holds is as good as plaintext. Imported cookies
 * therefore never go there:
 *
 * - they are sealed with Emperor's local key, bound to the profile (the
 *   context names its folder), in `browser/profiles/<id>/imported-cookies.el1`
 *   (0600, written to a private file and renamed into place);
 * - they are set into the profile's session as session cookies (no expiry),
 *   which Chromium keeps in memory only: at import, and when the session is
 *   first used in a run, before its first page loads. Expired ones are
 *   dropped; their expiry stays in the sealed file.
 *
 * Cookies a site sets while the Agent browses are Chromium's, saved its
 * usual way. The profile folder holding them is excluded from Time Machine.
 * Clearing the profile deletes the sealed file. Logs never carry a value.
 */
import { randomBytes } from 'node:crypto'
import {
  chmodSync,
  closeSync,
  fsyncSync,
  mkdirSync,
  openSync,
  readFileSync,
  renameSync,
  rmSync,
  statSync,
  writeSync,
} from 'node:fs'
import { join } from 'node:path'
import type { CookieSink, CookieToSet } from '../browser-import/import-service'
import { createBackupExclusion } from '../backup-exclusion'

export const IMPORTED_COOKIES_FILE = 'imported-cookies.el1'

/** Persistent profile ids are generated by Core: `p_` + 12 hex. */
const PROFILE_ID = /^p_[0-9a-f]{12}$/
const FORMAT_VERSION = 1
const SAME_SITE = new Set(['unspecified', 'no_restriction', 'lax', 'strict'])

/** Emperor's local key (`LocalSecretStore`). */
export interface SealedStorage {
  encryptString(value: string, context?: string): Buffer
  decryptString(data: Buffer, context?: string): string
}

/** What a cookie is set with in memory: no expiry, so never on disk. */
export type InMemoryCookie = Omit<CookieToSet, 'expirationDate'>

/** The part of an Electron session cookies are set into. */
export interface CookieSessionLike {
  readonly cookies: { set(details: InMemoryCookie): Promise<void> }
}

export interface ImportedCookieStoreOptions {
  /** `<stateRoot>/browser/profiles`. */
  readonly profilesRoot: string
  readonly storage: SealedStorage
  /** `session.fromPath` (main), for `sinkFor`. */
  sessionFromPath?(path: string): CookieSessionLike
  /** Keeps a folder out of Time Machine; default `tmutil addexclusion`. */
  excludeFromBackup?(path: string): Promise<void>
  now?(): number
  /** Value-free notes; default `console.warn`. */
  log?(message: string): void
}

function inMemory(cookie: CookieToSet): InMemoryCookie {
  const { expirationDate: _expiry, ...rest } = cookie
  return rest
}

/** Same name, domain (or host) and path: the later one replaces it. */
function cookieKey(cookie: CookieToSet): string {
  let host = cookie.domain ?? ''
  if (!host)
    try {
      host = new URL(cookie.url).hostname
    } catch {
      host = cookie.url
    }
  return `${host}\n${cookie.path}\n${cookie.name}`
}

function storedCookie(value: unknown): CookieToSet | null {
  if (value === null || typeof value !== 'object') return null
  const item = value as Record<string, unknown>
  if (
    typeof item.url !== 'string' ||
    typeof item.name !== 'string' ||
    typeof item.value !== 'string' ||
    typeof item.path !== 'string' ||
    typeof item.secure !== 'boolean' ||
    typeof item.httpOnly !== 'boolean' ||
    typeof item.sameSite !== 'string' ||
    !SAME_SITE.has(item.sameSite) ||
    (item.domain !== undefined && typeof item.domain !== 'string') ||
    (item.expirationDate !== undefined &&
      (typeof item.expirationDate !== 'number' ||
        !Number.isFinite(item.expirationDate)))
  )
    return null
  return {
    url: item.url,
    name: item.name,
    value: item.value,
    path: item.path,
    secure: item.secure,
    httpOnly: item.httpOnly,
    sameSite: item.sameSite as CookieToSet['sameSite'],
    ...(item.domain === undefined ? {} : { domain: item.domain }),
    ...(item.expirationDate === undefined
      ? {}
      : { expirationDate: item.expirationDate as number }),
  }
}

export class ImportedCookieStore {
  /** Sessions already given their imported cookies in this run. */
  private readonly prepared = new WeakMap<CookieSessionLike, Promise<void>>()
  /** Folders already handed to Time Machine exclusion in this run. */
  private readonly excluded = new Set<string>()
  private readonly excludeFromBackup: (path: string) => Promise<void>
  private readonly now: () => number
  private readonly log: (message: string) => void

  constructor(private readonly options: ImportedCookieStoreOptions) {
    this.excludeFromBackup =
      options.excludeFromBackup ?? createBackupExclusion()
    this.now = options.now ?? Date.now
    this.log = options.log ?? ((message) => console.warn(message))
  }

  private directory(profileId: string): string {
    if (!PROFILE_ID.test(profileId))
      throw new Error('invalid browser profile id')
    return join(this.options.profilesRoot, profileId)
  }

  /** Where a profile's imported cookies are sealed. */
  filePath(profileId: string): string {
    return join(this.directory(profileId), IMPORTED_COOKIES_FILE)
  }

  /** The sealing context: the file opens only for its own profile. */
  private context(profileId: string): string {
    return `browser/profiles/${profileId}/${IMPORTED_COOKIES_FILE}`
  }

  /** The profile folder exists, is private and is kept out of Time Machine. */
  private async ensureDirectory(directory: string): Promise<void> {
    mkdirSync(directory, { recursive: true, mode: 0o700 })
    if ((statSync(directory).mode & 0o077) !== 0) chmodSync(directory, 0o700)
    if (this.excluded.has(directory)) return
    this.excluded.add(directory)
    await this.excludeFromBackup(directory).catch((cause: unknown) => {
      this.log(
        `A browser profile folder could not be excluded from Time Machine: ${cause instanceof Error ? cause.message : String(cause)}`,
      )
    })
  }

  /** The cookies imported into a profile; empty when none or unreadable. */
  load(profileId: string): CookieToSet[] {
    const path = this.filePath(profileId)
    let data: Buffer
    try {
      data = readFileSync(path)
    } catch (cause) {
      if ((cause as NodeJS.ErrnoException).code !== 'ENOENT')
        this.log('The imported cookies of a browser profile could not be read')
      return []
    }
    try {
      const parsed = JSON.parse(
        this.options.storage.decryptString(data, this.context(profileId)),
      ) as { version?: unknown; cookies?: unknown }
      if (parsed.version !== FORMAT_VERSION || !Array.isArray(parsed.cookies))
        throw new Error('unknown format')
      return parsed.cookies.flatMap((item) => {
        const cookie = storedCookie(item)
        return cookie === null ? [] : [cookie]
      })
    } catch {
      // Another key, another profile's file, or damage: sign in or import
      // again. The file stays until then (or until the profile is cleared).
      this.log(
        'The imported cookies of a browser profile could not be opened with this Mac’s Emperor key',
      )
      return []
    }
  }

  /** Seal `cookies` into the profile's file, over earlier imports of theirs. */
  async save(
    profileId: string,
    cookies: readonly CookieToSet[],
  ): Promise<void> {
    const directory = this.directory(profileId)
    await this.ensureDirectory(directory)
    const nowSeconds = this.now() / 1000
    const merged = new Map<string, CookieToSet>()
    for (const cookie of [...this.load(profileId), ...cookies])
      if (
        cookie.expirationDate === undefined ||
        cookie.expirationDate > nowSeconds
      )
        merged.set(cookieKey(cookie), cookie)
    const sealed = this.options.storage.encryptString(
      JSON.stringify({
        version: FORMAT_VERSION,
        cookies: [...merged.values()],
      }),
      this.context(profileId),
    )
    const path = join(directory, IMPORTED_COOKIES_FILE)
    const temp = join(
      directory,
      `.${IMPORTED_COOKIES_FILE}.${randomBytes(6).toString('hex')}.tmp`,
    )
    const fd = openSync(temp, 'wx', 0o600)
    try {
      writeSync(fd, sealed)
      fsyncSync(fd)
    } finally {
      closeSync(fd)
    }
    try {
      renameSync(temp, path)
    } catch (cause) {
      rmSync(temp, { force: true })
      throw cause
    }
  }

  /**
   * The import's sink for one profile: each cookie goes into the session in
   * memory (one Electron refuses is skipped by the importer), and `flush`
   * seals the accepted ones.
   */
  sink(profileId: string, session: CookieSessionLike): CookieSink {
    this.directory(profileId)
    const accepted: CookieToSet[] = []
    return {
      set: async (cookie) => {
        await session.cookies.set(inMemory(cookie))
        accepted.push(cookie)
      },
      flush: async () => {
        await this.save(profileId, accepted)
      },
    }
  }

  /** `sink` on the profile's own session (`session.fromPath`). */
  sinkFor(profileId: string): CookieSink {
    const fromPath = this.options.sessionFromPath
    if (fromPath === undefined)
      throw new Error('profile sessions are not available')
    return this.sink(profileId, fromPath(this.directory(profileId)))
  }

  /**
   * Before a profile's first page in this run: keep its folder out of Time
   * Machine and set its imported cookies into the session, once (tabs
   * opening together share it).
   */
  prepare(profileId: string, session: CookieSessionLike): Promise<void> {
    const known = this.prepared.get(session)
    if (known !== undefined) return known
    const work = this.inject(profileId, session)
    this.prepared.set(session, work)
    // A failure (the folder could not be made) is tried again next time.
    work.catch(() => {
      if (this.prepared.get(session) === work) this.prepared.delete(session)
    })
    return work
  }

  private async inject(
    profileId: string,
    session: CookieSessionLike,
  ): Promise<void> {
    await this.ensureDirectory(this.directory(profileId))
    const nowSeconds = this.now() / 1000
    const live = this.load(profileId).filter(
      (cookie) =>
        cookie.expirationDate === undefined ||
        cookie.expirationDate > nowSeconds,
    )
    let refused = 0
    await Promise.all(
      live.map((cookie) =>
        session.cookies.set(inMemory(cookie)).catch(() => {
          refused += 1
        }),
      ),
    )
    if (refused > 0)
      this.log(`${refused} imported cookie(s) were refused by the browser`)
  }

  /** The profile was cleared or deleted: its imported cookies go too. */
  async cleared(profileId: string, session: CookieSessionLike): Promise<void> {
    this.prepared.delete(session)
    rmSync(this.filePath(profileId), { force: true })
  }
}
